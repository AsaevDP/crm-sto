"""Штрихкод Code 128 в SVG — без сторонних библиотек и без интернета (правило проекта).
Читается любым сканером штрихкодов (USB-сканер «печатает» код как клавиатура)."""

# Ширины полос/пробелов для значений 0–106 (стандарт Code 128). 106 — «стоп» (7 элементов).
_P = ("212222 222122 222221 121223 121322 131222 122213 122312 132212 221213 221312 231212 112232 122132 122231 "
      "113222 123122 123221 223211 221132 221231 213212 223112 312131 311222 321122 321221 312212 322112 322211 "
      "212123 212321 232121 111323 131123 131321 112313 132113 132311 211313 231113 231311 112133 112331 132131 "
      "113123 113321 133121 313121 211331 231131 213113 213311 213131 311123 311321 331121 312113 312311 332111 "
      "314111 221411 431111 111224 111422 121124 121421 141122 141221 112214 112412 122114 122411 142112 142211 "
      "241211 221114 413111 241112 134111 111242 121142 121241 114212 124112 124211 411212 421112 421211 212141 "
      "214121 412121 111143 111341 131141 114113 114311 411113 411311 113141 114131 311141 411131 211412 211214 "
      "211232 2331112").split()
START_B, START_C, STOP = 104, 105, 106


def encode(text: str) -> list[int]:
    """Значения символов с проверочной суммой. Только цифры чётной длины — набор C (короче), иначе набор B."""
    if text.isdigit() and len(text) % 2 == 0 and text:
        vals = [START_C] + [int(text[i:i + 2]) for i in range(0, len(text), 2)]
    else:
        vals = [START_B] + [ord(ch) - 32 for ch in text if 32 <= ord(ch) <= 126]
    check = (vals[0] + sum(v * i for i, v in enumerate(vals[1:], start=1))) % 103
    return vals + [check, STOP]


def modules(text: str) -> list[int]:
    """Последовательность ширин: полоса, пробел, полоса… (в «модулях»)."""
    out = []
    for v in encode(text):
        out += [int(c) for c in _P[v]]
    return out


def svg(text: str, height: int = 40, module: float = 1.0, quiet: int = 10) -> str:
    """SVG-картинка штрихкода. Масштабируется под размер наклейки (viewBox, preserveAspectRatio=none)."""
    ws = modules(text)
    total = sum(ws) + quiet * 2
    x, bars = quiet, []
    for i, w in enumerate(ws):
        if i % 2 == 0:
            bars.append(f'<rect x="{x}" y="0" width="{w}" height="{height}"/>')
        x += w
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {total} {height}" preserveAspectRatio="none" '
            f'class="bc" role="img" aria-label="Штрихкод {text}"><g fill="#000">{"".join(bars)}</g></svg>')
