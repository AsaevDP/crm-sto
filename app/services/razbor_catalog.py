def _stem(word: str) -> str:
    w = word.lower().strip("()/.,«»")
    return w[:max(4, len(w) - 2)] if len(w) > 5 else w


_INDEX = None


def _index():
    """[(ключевые основы слов детали, категория, подкатегория, название)] — длинные названия первыми."""
    global _INDEX
    if _INDEX is None:
        rows = []
        for cname, subs in CATALOG:
            for sname, parts in subs:
                for part in parts:
                    words = [_stem(w) for w in re.split(r"[\s/()\-]+", part) if len(w) >= 3]
                    if words:
                        rows.append((words, cname, sname, part))
        rows.sort(key=lambda r: -len(r[0]))
        _INDEX = rows
    return _INDEX


