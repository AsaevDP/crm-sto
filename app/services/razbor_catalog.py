def _norm(s: str) -> str:
    return " ".join((s or "").split()).lower()


def apply(db: Session, branch_id) -> dict:
    """Завести категории справочника (недостающие), один раз перенести детали из старых категорий."""
    from ..models import PartCatalog, RazborCategory, StockItem
    from . import settings as st
    done = st.get(db, branch_id, "razbor_catalog").get("v", 0)
    if done >= VERSION:
        return {"added": 0, "moved": 0, "removed": 0}   # уже заведено — дальше категории ведут люди (добавляют, убирают)
    if done >= 1:
        return _v2(db, branch_id)
    cats = db.scalars(select(RazborCategory).where(RazborCategory.branch_id == branch_id)).all()
    top = {_norm(c.name): c for c in cats if not c.parent_id}
    added = 0
    for n, (cname, subs) in enumerate(CATALOG, 1):
        c = top.get(_norm(cname))
        if c is None:
            c = RazborCategory(branch_id=branch_id, name=cname, sort=n)
            db.add(c)
            db.flush()
            top[_norm(cname)] = c
            added += 1
        else:
            c.sort = n
        have = {_norm(x.name) for x in cats if x.parent_id == c.id}
        for k, (sname, _parts) in enumerate(subs, 1):
            if _norm(sname) not in have:
                db.add(RazborCategory(branch_id=branch_id, name=sname, parent_id=c.id, sort=k))
                have.add(_norm(sname))
    db.flush()
    moved = removed = 0
    if done < 1:
        old = {_norm(k): v for k, v in OLD_MAP.items()}
        rows = db.execute(select(PartCatalog).join(StockItem, StockItem.catalog_id == PartCatalog.id)
                          .where(StockItem.branch_id == branch_id, PartCatalog.kind == "used")).scalars().unique().all()
        for p in rows:
            m = old.get(_norm(p.category))
            if not m:
                continue
            nc, ns = m.get(" ".join((p.subcategory or "").split())) or m["*"]
            if not ns:   # подкатегорию (а то и категорию точнее: «Блок ABS» — тормоза) угадаем по названию детали
                gc, gs = guess(p.name)
                if gc != "Прочее":
                    nc, ns = gc, gs
            p.category, p.subcategory = nc, ns
            moved += 1
        db.flush()
        # старые категории без деталей — из списка убрать (свои, добавленные людьми, не трогаем)
        used = {_norm(c) for c, in db.execute(select(PartCatalog.category).join(StockItem, StockItem.catalog_id == PartCatalog.id)
                                              .where(StockItem.branch_id == branch_id, PartCatalog.kind == "used"))}
        for c in list(top.values()):
            if _norm(c.name) in old and _norm(c.name) not in {_norm(x) for x, _ in CATALOG} and _norm(c.name) not in used:
                for s in db.scalars(select(RazborCategory).where(RazborCategory.parent_id == c.id)):
                    db.delete(s)
                db.delete(c)
                removed += 1
        db.flush()
    r = _v2(db, branch_id)
    return {"added": added, "moved": moved, "removed": removed + r["removed"]}


def _v2(db: Session, branch_id) -> dict:
    """Один раз: старые категории (в т.ч. дубли «Кузов»/«Кузов ») без деталей — убрать; деталям без подкатегории
    в перенесённых категориях — угадать подкатегорию (и точнее категорию)."""
    from ..models import PartCatalog, RazborCategory, StockItem
    from . import settings as st
    new_names = {_norm(x) for x, _ in CATALOG}
    old = {_norm(k) for k in OLD_MAP}
    rows = db.execute(select(PartCatalog).join(StockItem, StockItem.catalog_id == PartCatalog.id)
                      .where(StockItem.branch_id == branch_id, PartCatalog.kind == "used")).scalars().unique().all()
    for p in rows:
        if not (p.subcategory or "").strip() and _norm(p.category) in new_names:
            gc, gs = guess(p.name)
            if gc != "Прочее" and gs:
                p.category, p.subcategory = gc, gs
    db.flush()
    used = {_norm(p.category) for p in rows}
    removed = 0
    for c in db.scalars(select(RazborCategory).where(RazborCategory.branch_id == branch_id,
                                                     RazborCategory.parent_id.is_(None))).all():
        if _norm(c.name) in old and _norm(c.name) not in new_names and _norm(c.name) not in used:
            for s in db.scalars(select(RazborCategory).where(RazborCategory.parent_id == c.id)):
                db.delete(s)
            db.delete(c)
            removed += 1
    st.put(db, branch_id, "razbor_catalog", {"v": VERSION})
    db.flush()
    return {"added": 0, "moved": 0, "removed": removed}


