def guess(name: str) -> tuple[str, str]:
    """Категория и подкатегория по названию детали: «Фара передняя левая» → («Освещение», «Передняя оптика»).
    Сначала ключевые слова (точнее), потом типовые детали справочника целиком. Не нашли — («Прочее», "")."""
    n = (name or "").lower().replace("ё", "е")
    for keys, c, s in KEYWORDS:
        if all(k.replace("ё", "е") in n for k in keys):
            return c, s
    best = None
    for words, c, s, _p in _index():
        hit = sum(1 for w in words if w.replace("ё", "е") in n)
        if hit == len(words) and len(words) >= 2:
            score = (hit, len(words))
            if best is None or score > best[0]:
                best = (score, c, s)
    return (best[1], best[2]) if best else ("Прочее", "")


def hints() -> list[dict]:
    """Подсказки для поля «Название»: типовая деталь + куда она попадёт."""
    out = []
    for cname, subs in CATALOG:
        for sname, parts in subs:
            for part in parts:
                out.append({"name": part[:1].upper() + part[1:], "cat": cname, "sub": sname})
    return out
